async function api(action, args = {}) {
  const r = await fetch(BASE + '/api', { method: 'POST', body: JSON.stringify({ action, ...args }) });
  return r.json();
}
async function data(action, args) {
  const j = await api(action, args);
  if (!j.ok) throw new Error(action + ': ' + j.error);
  return j.data;
}
async function upload(start, args, bytes, type = 'application/octet-stream', name = 'file.bin') {
  const { uploadUrl, chunkSize } = await data(start, { ...args, name, mimeType: type, size: bytes.length });
  if (bytes.length <= chunkSize) {
    const r = await (await fetch(uploadUrl, { method: 'PUT', body: bytes })).json();
    if (!r.ok) throw new Error('put: ' + r.error);
    return r.data.fileId;
  }
  const parts = [];
  for (let s = 0, n = 1; s < bytes.length; s += chunkSize, n++) {
    const r = await (await fetch(`${uploadUrl}?part=${n}`, { method: 'PUT', body: bytes.slice(s, s + chunkSize) })).json();
    if (!r.ok) throw new Error('part: ' + r.error);
    parts.push(r.data);
  }
  const r = await (await fetch(uploadUrl, { method: 'POST', body: JSON.stringify({ parts }) })).json();
  if (!r.ok) throw new Error('complete: ' + r.error);
  return r.data.fileId;
}
